const ALIASES = {
  '×': 'X', '’': "'", '‘': "'", '“': '"', '”': '"', '–': '-', '—': '-', '…': '...',
};

export function normalize(str) {
  let s = String(str);
  for (const [from, to] of Object.entries(ALIASES)) s = s.split(from).join(to);
  return s.normalize('NFD').replace(/[̀-ͯ]/g, '').toUpperCase();
}

export function supports(str) {
  return [...normalize(str)].every((ch) => G[ch]);
}

export function textWidth(str, scale = 1) {
  const n = [...normalize(str)].length;
  return n ? (n * ADVANCE - 1) * scale : 0;
}

// One subpath per horizontal run of ink, which keeps the path short.
export function textPath(str, x, y, scale = 1) {
  let d = '';
  let cx = x;
  for (const ch of normalize(str)) {
    const glyph = G[ch] || G['?'];
    glyph.forEach((row, ry) => {
      let start = -1;
      for (let rx = 0; rx <= GLYPH_W; rx++) {
        const ink = row[rx] === '#';
        if (ink && start < 0) start = rx;
        if (!ink && start >= 0) {
          const w = (rx - start) * scale;
          d += `M${cx + start * scale} ${y + ry * scale}h${w}v${scale}h-${w}z`;
          start = -1;
        }
      }
    });
    cx += ADVANCE * scale;
  }
  return d;
}

// Greedy word wrap on character count (the font is monospaced).
export function wrap(str, maxChars) {
  const lines = [];
  let line = '';
  for (const word of normalize(str).split(/\s+/).filter(Boolean)) {
    if (!line) line = word;
    else if (line.length + 1 + word.length <= maxChars) line += ' ' + word;
    else {
      lines.push(line);
      line = word;
    }
  }
  if (line) lines.push(line);
  return lines;
}
